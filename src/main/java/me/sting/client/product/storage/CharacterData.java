package me.sting.client.product.storage;

public class CharacterData
{
    public int x;
    public int height;
    public int y;
    public int width;
    
    public void setX(final int x) {
        this.x = x;
    }
    
    public void setHeight(final int height) {
        this.height = height;
    }
    
    public void setY(final int y) {
        this.y = y;
    }
    
    public void setWidth(final int width) {
        this.width = width;
    }
}
